// ============================================================
// version.cpp —— 协议版本号的存在意义与它的盲区
// ============================================================
//
// 【作用】
// 协议版本（EM_PROTO_VERSION）是"空口帧格式 / 封装语义的兼容性编号"。
// 它由每周期广播、所有节点都会收到的 BEACON 携带（1 字节），收端把自己的
// 版本与对端版本比对，不一致时只做三件事：计数、串口告警、CLI 显示。
// 目的是拦住"改了帧头两端悄悄不兼容"这类问题——现场表现为时通时不通或
// 完全不通时，能一眼看出是版本问题还是射频问题。
//
// 【只能拦未来的不一致 —— 必须诚实说明】
// 这套机制只能拦住"未来"的版本不一致（比如 v2↔v3）：两端都能正常解出帧，
// 于是能读到 payload 里的版本号并比对。对已经发生的 14/15 字节帧头不兼容
// （v1↔v2）无能为力——旧固件（v1）连帧都解不出来，frame_decode 的长度校验
// 与 CRC 校验直接失败，根本走不到"读 payload 里的版本号"这一步。
//
// 【只告警不拒绝】
// 版本不一致时仍照常收/转，不丢包。因为还要能互相看见（例如对端版本号能
// 显示出来），便于现场判断到底该刷哪一台，而不是把链路直接掐死。
//
// ============================================================
#include "version.h"

const char* version_fw_str(void) {
    return EM_FW_VERSION;
}

const char* version_proto_str(void) {
    static char buf[8];
    snprintf(buf, sizeof(buf), "v%u", (unsigned)EM_PROTO_VERSION);
    return buf;
}
